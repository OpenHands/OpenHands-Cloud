#!/usr/bin/env python3
"""Generate the support bundle collector that records Admin Console settings.

A support bundle shows what the pods ended up with, but not what the customer
chose on the Admin Console Config page, and only some settings reach a pod as
an environment variable. This writes replicated/support-bundle.yaml: a KOTS
SupportBundle spec whose one data collector saves every non-secret config item
as `name: value` under kots/admin-console/config.yaml, grouped as on the page.

KOTS renders the ConfigOption template functions when the release is deployed
(and merges this spec with the chart's own) — re-rendering on every config
change, so the file reflects the install's ConfigValues as of the last apply,
including defaults. Each value is JSON-quoted with mustToJson so multi-line
textareas stay on one line.

Items are skipped when their type is password or file, when they are labels
with no value, or when they are named in EXCLUDED because the value pairs with
a secret or could carry one. Everything else is included, so a new config item
shows up in bundles without anyone remembering to add it.

Usage:
    scripts/support_bundle_config.py          # rewrite the manifest
    scripts/support_bundle_config.py --check  # exit 1 if it is out of date
"""

import argparse
import pathlib
import sys

import yaml

ROOT = pathlib.Path(__file__).resolve().parents[1]
CONFIG = ROOT / "replicated" / "config.yaml"
MANIFEST = ROOT / "replicated" / "support-bundle.yaml"
BUNDLE_PATH = "kots/admin-console/config.yaml"

SECRET_TYPES = {"password", "file"}
VALUELESS_TYPES = {"label", "heading"}
# Non-password items that still must not be collected.
EXCLUDED = {
    # Account identifiers that pair with a password and are already hashed into
    # secretsChecksum in replicated/openhands.yaml.
    "aws_access_key_id",
    "jira_data_center_service_account_email",
    "smtp_username",
    # Free-form headers, which customers use for upstream auth tokens.
    "custom_llm_extra_headers",
}

HEADER = f"""\
# Generated by scripts/support_bundle_config.py from replicated/config.yaml.
# Do not edit by hand: run the script, and keep the two in sync (the check
# runs in CI from scripts/test_support_bundle_config.py).
#
# Saves the non-secret Admin Console settings to {BUNDLE_PATH} in each
# support bundle. KOTS renders the values when the release is deployed (and
# merges this spec with the chart's), re-rendering on every config change.
# Password and file items are left out, as are the items the generator names
# in EXCLUDED. A value is recorded whether or not its item is currently shown
# (its `when` condition is not evaluated here).
apiVersion: troubleshoot.sh/v1beta2
kind: SupportBundle
metadata:
  name: openhands-admin-console-config
spec:
  collectors:
    - data:
        name: {BUNDLE_PATH}
        data: |
"""


def collected_items(config: dict) -> list[tuple[dict, list[dict]]]:
    """The (group, items) pairs the collector records, in page order."""
    groups = []
    for group in config["spec"]["groups"]:
        items = [
            item
            for item in group.get("items") or []
            if item.get("type") not in SECRET_TYPES | VALUELESS_TYPES
            and item["name"] not in EXCLUDED
        ]
        if items:
            groups.append((group, items))
    return groups


def render(config: dict) -> str:
    lines = [HEADER.rstrip("\n")]
    for group, items in collected_items(config):
        title = group.get("title") or group["name"]
        lines.append(f"          # {title}")
        lines.append(f"          {group['name']}:")
        for item in items:
            name = item["name"]
            lines.append(f'            {name}: repl{{{{ ConfigOption "{name}" | mustToJson }}}}')
    return "\n".join(lines) + "\n"


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__.split("\n\n")[0])
    parser.add_argument("--check", action="store_true", help="fail if the manifest is out of date")
    args = parser.parse_args(argv)

    expected = render(yaml.safe_load(CONFIG.read_text()))
    if args.check:
        current = MANIFEST.read_text() if MANIFEST.exists() else ""
        if current != expected:
            print(f"{MANIFEST.relative_to(ROOT)} is out of date; run scripts/support_bundle_config.py")
            return 1
        print(f"{MANIFEST.relative_to(ROOT)} is up to date")
        return 0
    MANIFEST.write_text(expected)
    print(f"wrote {MANIFEST.relative_to(ROOT)}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
